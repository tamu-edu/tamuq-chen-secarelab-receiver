"""Generate manuscript Tables 1 and 2 from the saved reduction products.

Runs no experiment reduction of its own: it reads the CSVs written by
`exp_analysis.py`, `dimensionless_analysis.py` and `uncertainty_analysis.py`
and emits the two manuscript tables in both machine- and manuscript-readable
form. Re-run after any change to the reduction so the tables cannot drift from
the data.

Inputs   (all in this directory)
  dimensionless_groups.csv     per-run dimensionless quantities
  uncertainty_per_run.csv      Monte Carlo standard deviations per run
  eigenvalue_verification.csv  slow-mode eigenvalues, heating and cooling
  delivered_power_check.csv    per-run delivered-power factors, K bracket
  steady_state_metrics.csv     steady means and t90 values

Outputs  (all in this directory)
  table1_campaign_envelope.csv / .md
  table2_identified_constants.csv / .md

Definitions follow Section 3.2 of the manuscript:
  Tw_bar = 0.248 T8 + 0.365 T12 + 0.387 T11,  eps = (T3-Tamb)/(Tw_bar-Tamb),
  NTU = -ln(1-eps),  I_vol = T12 - T8.
Eigenvalue identification follows Section 4.7: lam = (eps*mdot*cp + K)/C, so a
regression of lam on x = eps*mdot*cp has slope 1/C and intercept K/C.
"""
import os
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
P = lambda f: os.path.join(HERE, f)
RNG = np.random.default_rng(7)
NMC = 20000
SIG_TC = 2.2 / 2.0          # type-N class tolerance, treated as 2 sigma


def ci(v, lo=2.5, hi=97.5):
    return np.percentile(v, lo), np.percentile(v, hi)


def fmt(v, c, nd=3):
    return f"{v:.{nd}f} [{c[0]:.{nd}f}, {c[1]:.{nd}f}]"


# --------------------------------------------------------------------------
# Table 1 - campaign and dimensionless envelope
# --------------------------------------------------------------------------
def table1():
    d = pd.read_csv(P("dimensionless_groups.csv"))
    u = pd.read_csv(P("uncertainty_per_run.csv"))
    m = pd.read_csv(P("steady_state_metrics.csv"))[["ID", "eta_gas", "eta_del"]]
    t = d.merge(u, on="ID").merge(m, on="ID")

    out = pd.DataFrame({
        "run": t.ID,
        "G0_kW_m2": t.Io_kWm2.round(0).astype(int),
        "q_sLmin": t.q_slpm.round(2),
        "mdot_g_s": t.mdot_gs.round(4),
        "Re": t.Re.round(1),
        "Re_sd": t.Re_sd.round(1),
        "Gz_L": t.Gz_L.round(3),
        "Tw_bar_K": t.Tw_K.round(1),
        "T3_K": t.T3_K.round(1),
        "eps": t.eps.round(3),
        "eps_sd": t.eps_sd.round(3),
        "NTU": t.NTU.round(3),
        "NTU_sd": t.NTU_sd.round(3),
        "Nu_app": t.Nu.round(4),
        "Nu_app_sd": t.Nu_sd.round(4),
        "Lambda_107": t.LTNE107.round(4),
        "I_vol_K": t.I_vol_wall.round(1),
        "PR_del_kJ_kg": t.PR_del_kJkg.round(0),
        "eta_gas": t.eta_gas.round(3),
        "eta_del": t.eta_del.round(3),
    }).sort_values(["G0_kW_m2", "q_sLmin"], ascending=[False, True])
    out.to_csv(P("table1_campaign_envelope.csv"), index=False)

    cols = ["run", "G0_kW_m2", "q_sLmin", "Re", "Gz_L", "Tw_bar_K", "T3_K",
            "eps", "NTU", "Nu_app", "Lambda_107", "I_vol_K", "eta_del"]
    hdr = ["Run", "G0 [kW m-2]", "q [sL min-1]", "Re", "Gz_L", "Tw_bar [K]",
           "T3 [K]", "eps", "NTU", "Nu_app", "L_107", "I_vol [K]", "eta_del"]
    md = ["**Table 1.** Experimental campaign and dimensionless envelope. "
          "Generated by `make_tables.py`.", "",
          "| " + " | ".join(hdr) + " |",
          "|" + "|".join(["---"] * len(hdr)) + "|"]
    for _, r in out.iterrows():
        md.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    md += ["", f"Envelope: Re {out.Re.min():.0f}-{out.Re.max():.0f}, "
               f"eps {out.eps.min():.3f}-{out.eps.max():.3f}, "
               f"NTU {out.NTU.min():.2f}-{out.NTU.max():.2f}, "
               f"Nu_app {out.Nu_app.min():.3f}-{out.Nu_app.max():.3f}."]
    open(P("table1_campaign_envelope.md"), "w").write("\n".join(md) + "\n")
    return out


